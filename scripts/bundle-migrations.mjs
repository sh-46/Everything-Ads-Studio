// Bundles supabase/migrations/*.sql into one file for a fresh project's SQL editor:
// supabase/setup/apply-all.sql. Runs in a single transaction and refuses to run on a
// database that already has the schema (so it can never be applied twice).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const body = files.map((f) => `-- ===== ${f} =====\n${readFileSync(new URL(f, dir), "utf8").trim()}\n`).join("\n");

const out = `-- Everything Ads Studio — full schema for a NEW Supabase project.
-- Generated by \`npm run db:bundle\` from: ${files.join(", ")}.
-- Paste into Supabase Dashboard → SQL Editor → Run. Additive only (creates tables,
-- functions, policies and the private "assets" bucket); never drops or deletes.
-- If the schema already exists it stops without changing anything: apply only the
-- migrations listed as missing in public.schema_versions instead.

begin;

do $guard$
begin
  if to_regclass('public.workspaces') is not null then
    raise exception 'Everything Ads schema already exists — nothing was changed. Apply only newer migration files.';
  end if;
end
$guard$;

${body}
commit;
`;
writeFileSync(new URL("../supabase/setup/apply-all.sql", import.meta.url), out);
console.log(`Wrote supabase/setup/apply-all.sql (${files.length} migrations)`);
